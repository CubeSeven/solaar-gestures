#!/usr/bin/env bash
# install.sh — wire a Logitech mouse (Solaar-diverted buttons) to GNOME actions.
#
# What it does:
#   1. preflight: GNOME Wayland, solaar, ydotool/ydotoold
#   2. backs up ~/.config/solaar/rules.yaml
#   3. installs bin/mouse-action + bin/mouse-doctor into ~/.local/bin
#   4. writes ~/.config/solaar/rules.yaml for the detected gesture/haptic controls
#   5. runs mouse-doctor (finds the combos that work here, writes keymap + gsettings)
#   6. restarts Solaar and checks the buttons are still diverted
#
# Usage: ./install.sh [--yes] [--no-doctor] [--mods "Shift+Alt"]
#                     [--gesture "Mouse Gesture Button"] [--haptic "Haptic"]

set -eu

YES=0
RUN_DOCTOR=1
MODS=""
GESTURE=""
HAPTIC=""
ASSUME_HAPTIC=1

while [ $# -gt 0 ]; do
    case "$1" in
        --yes|-y) YES=1 ;;
        --no-doctor) RUN_DOCTOR=0 ;;
        --mods) shift; MODS="${1:-}" ;;
        --gesture) shift; GESTURE="${1:-}" ;;
        --haptic) shift; HAPTIC="${1:-}" ;;
        --no-haptic) ASSUME_HAPTIC=0 ;;
        -h|--help) sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

SRC=$(cd -- "$(dirname -- "$0")" && pwd)
BIN_DIR="$HOME/.local/bin"
RULES="$HOME/.config/solaar/rules.yaml"
STAMP=$(date +%Y%m%d-%H%M%S)

say()  { printf '%s\n' "$*"; }
ok()   { printf '  [ok]   %s\n' "$*"; }
bad()  { printf '  [fail] %s\n' "$*"; }
warn() { printf '  [warn] %s\n' "$*"; }

say "solaar-gestures installer"
say "-------------------------"

# ---------------------------------------------------------------- preflight --
[ "${XDG_SESSION_TYPE:-}" = wayland ] || warn "not a Wayland session (${XDG_SESSION_TYPE:-unknown}) — targeted at GNOME Wayland"
case "${XDG_CURRENT_DESKTOP:-}" in
    *GNOME*) ok "GNOME session" ;;
    *) warn "desktop '${XDG_CURRENT_DESKTOP:-unknown}' — GNOME expected" ;;
esac
command -v solaar >/dev/null || { bad "solaar not installed"; exit 1; }
ok "solaar found"
command -v ydotool >/dev/null || { bad "ydotool not installed (pacman -S ydotool)"; exit 1; }
ok "ydotool found"
if ! systemctl --user is-active --quiet ydotool.service 2>/dev/null; then
    bad "ydotoold not running — run: systemctl --user enable --now ydotool.service"; exit 1
fi
ok "ydotoold running"
case ":$PATH:" in
    *":$BIN_DIR:"*) ok "$BIN_DIR on PATH" ;;
    *) warn "$BIN_DIR is not on PATH — Solaar rules use absolute paths, so this still works, but add it for convenience" ;;
esac

# ------------------------------------------------------------ detect buttons --
detect_controls() {
    solaar show 2>/dev/null | strings |
        sed -n 's/^[[:space:]]*Key\/Button Diversion (saved): *{\(.*\)}.*/\1/p' |
        tr ',' '\n' | sed 's/^[[:space:]]*//' | cut -d: -f1
}
CONTROLS=$(detect_controls)
if [ -z "$CONTROLS" ]; then
    bad "no diverted controls found — is the mouse connected and seen by Solaar?"
    exit 1
fi
say ""
say "controls found:"
printf '  %s\n' $CONTROLS

[ -n "$GESTURE" ] || GESTURE=$(printf '%s\n' "$CONTROLS" | grep -i 'gesture' | head -1 || true)
if [ -z "$GESTURE" ]; then
    bad "could not find a gesture button — pass --gesture '<control name>'"
    exit 1
fi
ok "gesture button: $GESTURE"

if [ -z "$HAPTIC" ] && [ "$ASSUME_HAPTIC" = 1 ]; then
    HAPTIC=$(printf '%s\n' "$CONTROLS" | grep -iE 'haptic' | head -1 || true)
fi
if [ -n "$HAPTIC" ]; then ok "second button: $HAPTIC"; else warn "no second (haptic) button — writing gesture rules only"; fi

# ------------------------------------------------------------------- confirm --
say ""
say "will write: $RULES (backup taken first)"
say "will install: $BIN_DIR/mouse-action, $BIN_DIR/mouse-doctor"
if [ "$YES" != 1 ]; then
    printf 'continue? [y/N] '
    read -r reply
    case "$reply" in y|Y|yes|YES) ;; *) say "aborted"; exit 1 ;; esac
fi

# ------------------------------------------------------------------ install --
mkdir -p "$BIN_DIR" "$HOME/.config/solaar"
if [ -f "$RULES" ]; then
    cp "$RULES" "$RULES.pre-gestures-$STAMP.bak"
    ok "backup: $RULES.pre-gestures-$STAMP.bak"
fi
install -m 755 "$SRC/bin/mouse-action" "$BIN_DIR/mouse-action"
install -m 755 "$SRC/bin/mouse-doctor" "$BIN_DIR/mouse-doctor"
ok "installed binaries"

rules_entry() {  # $1 control, $2 gesture suffix, $3 action
    local g="[$1]" a="$3"
    [ -n "$2" ] && g="[$1, $2]"
    printf -- '---\n- MouseGesture: %s\n- Execute: ["%s/mouse-action", "%s"]\n' "$g" "$BIN_DIR" "$a"
}

{
    printf '%%YAML 1.3\n'
    printf -- '# generated by solaar-gestures — actions run through %s/mouse-action\n' "$BIN_DIR"
    rules_entry "$GESTURE" "" overview
    rules_entry "$GESTURE" "Mouse Left" ws_prev
    rules_entry "$GESTURE" "Mouse Right" ws_next
    rules_entry "$GESTURE" "Mouse Up" overview
    rules_entry "$GESTURE" "Mouse Down" showdesk
    if [ -n "$HAPTIC" ]; then
        rules_entry "$HAPTIC" "" appgrid
        rules_entry "$HAPTIC" "Mouse Left" ws_prev
        rules_entry "$HAPTIC" "Mouse Right" hermes
        rules_entry "$HAPTIC" "Mouse Up" overview
        rules_entry "$HAPTIC" "Mouse Down" showdesk
    fi
    printf '...\n'
} > "$RULES"
ok "rules written"

# ------------------------------------------------------------------- doctor --
if [ "$RUN_DOCTOR" = 1 ]; then
    say ""
    if [ -n "$MODS" ]; then
        "$BIN_DIR/mouse-doctor" --mods "$MODS"
    else
        "$BIN_DIR/mouse-doctor"
    fi
else
    warn "skipped mouse-doctor — run it yourself: mouse-doctor"
fi

# ------------------------------------------------------------- restart solaar --
say ""
pkill -x solaar 2>/dev/null || true
sleep 1
( setsid solaar --window=hide >/dev/null 2>&1 & ) || true
sleep 5
if pgrep -x solaar >/dev/null; then ok "solaar restarted"; else bad "solaar did not start — start it manually"; fi

# diversion is a device-side setting: without "Mouse Gestures" the rules never fire
div=$(solaar show 2>/dev/null | strings | sed -n 's/.*Key\/Button Diversion (saved): *{\(.*\)}.*/\1/p' | head -1)
say ""
if printf '%s' "$div" | grep -q "$GESTURE:Mouse Gestures"; then
    ok "$GESTURE diverted as Mouse Gestures"
else
    warn "$GESTURE is not set to 'Mouse Gestures'"
    say "       open Solaar → your mouse → Key/Button Diversion → set '$GESTURE' to Mouse Gestures"
fi

say ""
say "done. Test with your hands:"
say "  gesture tap        → overview"
say "  gesture left/right → previous / next workspace"
say "  gesture down       → show desktop"
say "  second button tap  → app launcher (if present)"
say ""
say "undo everything: $SRC/uninstall.sh"
